import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import { unzipSync } from 'fflate';
import assert from 'node:assert/strict';
const pkg=JSON.parse(await fs.readFile('package.json')),version=pkg.version;
const target=await fs.mkdtemp(path.resolve('release/smoke-'));
await fs.writeFile(path.join(target,'package.json'),JSON.stringify({private:true,type:'module'}));
execFileSync(process.execPath,[process.env.npm_execpath,'install','--ignore-scripts','--no-audit','--no-fund','--prefix',target,path.resolve(`release/shadow-image-${version}.tgz`)],{stdio:'pipe'});
await fs.writeFile(path.join(target,'check.mjs'),"import { ShadowImageDecoder, ShadowImagePlayer } from 'shadow-image'; import { encode } from 'shadow-image/encoder'; if (![ShadowImageDecoder, ShadowImagePlayer, encode].every(x=>typeof x==='function')) throw Error('Package exports missing'); console.log('npm install and package exports verified.');");
execFileSync(process.execPath,[path.join(target,'check.mjs')],{stdio:'inherit'});
execFileSync('tar',['-xzf',path.resolve(`release/shadow-image-${version}.tgz`),'-C',target]);
const {encode}=await import(pathToFileURL(path.join(target,'package/dist/encoder.js')));
const {ShadowImageDecoder}=await import(pathToFileURL(path.join(target,'package/dist/index.js')));
const rgba=Uint8Array.from({length:37*35*4},(_,i)=>(i*71)&255);let final;
const d=new ShadowImageDecoder({onFrame:f=>{if(f.final)final=f.rgba;}});d.push(encode(rgba,{width:37,height:35}));d.finish();assert.deepEqual(final,new Uint8ClampedArray(rgba));
const archive=unzipSync(await fs.readFile(`release/shadow-image-browser-${version}.zip`)),root=`shadow-image-${version}`;
for(const name of ['index.html','sample.shp','dist/index.js','dist/player/worker.js','README.md','LICENSE'])assert.ok(archive[`${root}/${name}`],name);
const sample=new ShadowImageDecoder();sample.push(archive[`${root}/sample.shp`]);sample.finish();
console.log('Release tarball imports, pixel round-trip, browser ZIP and sample verified.');
